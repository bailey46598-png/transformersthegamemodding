"""Turns a level (TestTranquility by default) into a combat testing hub.

What it writes into the level folder (originals kept once as *.hub.bak; re-running gives the same result):
  AI/LEVEL.SCP     the level script, with one state per opponent and mode, plus HubClear / HubGoArena / HubIdle.
                   The DebugTrainer's "Opponents" panel loads the character, then fires one of these states.
  PLACEMENTS.INI   + placement HubArena (where you start and respawn)
  SPLINE.DAT       + spline HubSpawn (where opponents appear, facing the arena)

Opponents = every CHARACTER in the level's CREATURES.CFG that is a whole creature: vehicle/transform/arm parts
and pedestrians are skipped. Re-run after adding characters to CREATURES.CFG.

usage: python make_hub.py [LEVEL_DIR] [--check]
  LEVEL_DIR defaults to ..\\..\\..\\Lab - VehicleJump\\LEVELS\\TESTTRANQUILITY
  --check  prints what it would write and changes nothing
  --modes=Fight,Dummy  only these modes (Fight, Boss, Dummy, Wave), for a smaller script
"""
import os, re, shutil, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
LEVEL = os.path.abspath(os.path.join(HERE, '..', '..', '..', 'Lab - VehicleJump', 'LEVELS', 'TESTTRANQUILITY'))

# Arena: the baseball field in Tranquility (collision is flat at about 12.8-13.6 here; measured with TF Studio).
ARENA = (-5.0, 14.0, 250.0)                       # player start, about 1 unit above the ground
SPAWN = [(-5.0, 14.6, 315.0), (-5.0, 14.6, 312.0)]  # opponent spawn point, then a point toward the player (facing)

# Script modes. {T} = creature type. Every state ends in HubIdle so the same state can be fired again.
COMMON = '"#Spline=HubSpawn" "#ForcePlayerAsOpp" "#SpawnAsCreature" "#SpawnInLOSInit" "#AddToRadarAlways"'
MODES = {
    'Fight': '"#Type={T}" "#Count=1" "#MaxAlive=1" "#Script=Combat" ' + COMMON,
    'Boss':  '"#Type={T}" "#Count=1" "#MaxAlive=1" "#Script=Combat" "#Boss" ' + COMMON,
    'Dummy': '"#Type={T}" "#Count=1" "#MaxAlive=1" "#Script=StandAndWait" ' + COMMON,
    'Wave':  '"#Type={T}" "#Count=3" "#MaxAlive=3" "#Script=Combat" ' + COMMON,
}
PART = re.compile(r'(Car|Tran|Veh|Heli|CutTran|Turret|Arm|LeftArm|RightArm|GunArm|Gun|Blade)$', re.I)


def read(p):
    return open(p, 'rb').read().decode('latin1')


def resolve(root, rel):
    """Case-insensitive path under root (the game uses Windows paths)."""
    cur = root
    for part in rel.replace('\\', '/').split('/'):
        if not part:
            continue
        hit = [x for x in os.listdir(cur) if x.lower() == part.lower()]
        if not hit:
            return None
        cur = os.path.join(cur, hit[0])
    return cur


def opponents(level_dir):
    game = os.path.abspath(os.path.join(level_dir, '..', '..'))
    names, seen = [], set()
    for line in read(os.path.join(level_dir, 'CREATURES.CFG')).splitlines():
        m = re.match(r'\s*INCLUDE\s+(\S+)', line)
        if not m:
            continue
        p = resolve(game, m.group(1))
        if not p:
            print('  missing include:', m.group(1))
            continue
        for c in re.findall(r'^\s*CHARACTER\s+(\S+)', read(p), re.M):
            k = c.lower()
            if k in seen or PART.search(c) or k.startswith('ped_'):
                continue
            seen.add(k)
            names.append(c)
    return names


def script(names):
    L = []
    w = L.append
    w('; Combat testing hub. Generated by Fresh Build\\mods\\CombatHub\\make_hub.py: edit that, not this file.')
    w('; The DebugTrainer "Opponents" panel loads a character, then fires Hub<Mode>_<Name>.')
    w('')
    w('state base\n{\n\tactions\n\t{')
    w('\t\tDrawConditionsFromThisScript')
    w('\t\tCreateModule "#General" "#General" "#ProtectSystem"')
    w('\t\tSendToModule "#General" "#AllowPlayerMovement"')
    w('\t\tSetState "Main"\n\t}\n}\n')
    w('state Main\n{\n\tactions\n\t{')
    # same order as the shipped levels: clear modules first, then message #General (a system module, it survives)
    w('\t\tDestroyAllModules "#IncludeProtected"')
    w('\t\tSendToModule "#General" "#ResetAll" "#SetPlayer=#HubArena" "#SetPlayerDeathPoint=#HubArena" "#FadeUp"')
    w('\t\tSetDeathPoint "Death"')
    w('\t\tSetState "HubIdle"\n\t}\n}\n')
    w('state Death\n{\n\tconditions\n\t{\n\t\tif module "General GetFinishedMissionDeathFail" == 1.0 goto Main\n\t}')
    w('\tactions\n\t{\n\t\tDestroyAllModules "#IncludeProtected"\n\t\tSendToModule "#General" "#DeathFailMission"\n\t}\n}\n')
    w('state HubIdle\n{\n\tactions\n\t{\n\t\tResetTimer\n\t}\n}\n')
    w('state HubClear\n{\n\tactions\n\t{\n\t\tDestroyModule "#HubOpp"\n\t\tSetState "HubIdle"\n\t}\n}\n')
    w('state HubGoArena\n{\n\tactions\n\t{\n\t\tSendToModule "#General" "#SetPlayer=#HubArena"\n\t\tSetState "HubIdle"\n\t}\n}\n')
    for n in names:
        for mode, args in MODES.items():
            w(f'state Hub{mode}_{n}\n{{\n\tactions\n\t{{')
            w('\t\tDestroyModule "#HubOpp"')
            w(f'\t\tCreateModule "#Creature" "#HubOpp" {args.replace("{T}", n)}')
            w('\t\tSetState "HubIdle"\n\t}\n}\n')
    return '\r\n'.join('\r\n'.join(x.split('\n')) for x in L) + '\r\n'


def placements(text):
    text = re.sub(r'\r?\nPlacement\r?\n\{\r?\n\tTagString = "HubArena"[\s\S]*?\}\r?\n?', '\r\n', text)
    x, y, z = ARENA
    block = ('Placement\r\n{\r\n\tTagString = "HubArena"\r\n'
             f'\tPosX = {int(round(x * 10))}\r\n\tPosY = {int(round(y * 10))}\r\n\tPosZ = {int(round(z * 10))}\r\n'
             '\tRotX = 0\r\n\tRotY = 0\r\n\tRotZ = 0\r\n\tScale = 10\r\n}\r\n')
    return text.rstrip('\r\n') + '\r\n' + block


def splines(data):
    n = struct.unpack_from('<I', data, 0)[0]
    out, o = [], 4
    for _ in range(n):
        name = data[o:o + 32]
        c = struct.unpack_from('<I', data, o + 32)[0]
        body = data[o:o + 36 + 12 * c]
        o += 36 + 12 * c
        if name.split(b'\0')[0].lower() != b'hubspawn':
            out.append(body)
    if o != len(data):
        raise ValueError('SPLINE.DAT did not parse to the end')
    nm = bytearray(b'\xcd' * 32); nm[:9] = b'HubSpawn\0'
    out.append(bytes(nm) + struct.pack('<I', len(SPAWN)) + b''.join(struct.pack('<3f', *p) for p in SPAWN))
    return struct.pack('<I', len(out)) + b''.join(out)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    check = '--check' in sys.argv
    for a in sys.argv[1:]:  # --modes=Fight,Dummy keeps only those modes (fewer states)
        if a.startswith('--modes='):
            keep = {m.strip().lower() for m in a[8:].split(',')}
            for m in list(MODES):
                if m.lower() not in keep:
                    del MODES[m]
    level = os.path.abspath(args[0]) if args else LEVEL
    names = opponents(level)
    print(f'{len(names)} opponents x {len(MODES)} modes:', ', '.join(names))
    files = {
        os.path.join(level, 'AI', 'LEVEL.SCP'): script(names).encode('latin1'),
        os.path.join(level, 'PLACEMENTS.INI'): None,
        os.path.join(level, 'SPLINE.DAT'): None,
    }
    for p in files:  # keep the originals once
        if not os.path.exists(p + '.hub.bak'):
            if check:
                print('  would back up', p)
            else:
                shutil.copy2(p, p + '.hub.bak')
    src = lambda p: p + '.hub.bak' if os.path.exists(p + '.hub.bak') else p
    files[os.path.join(level, 'PLACEMENTS.INI')] = placements(read(src(os.path.join(level, 'PLACEMENTS.INI')))).encode('latin1')
    files[os.path.join(level, 'SPLINE.DAT')] = splines(open(src(os.path.join(level, 'SPLINE.DAT')), 'rb').read())
    for p, data in files.items():
        if check:
            print(f'  would write {p} ({len(data)} bytes)')
        else:
            open(p, 'wb').write(data)
            print(f'  wrote {p} ({len(data)} bytes)')


if __name__ == '__main__':
    main()
